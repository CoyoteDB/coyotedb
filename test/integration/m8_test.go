// Integration tests for milestone M8: `coyote migrate`. (Checked tables are
// leaf tables: a partitioned parent holds no rows of its own.) The source is a
// separate, plain PostgreSQL started from the bundled binaries on a spare
// port; the target is a real cluster of agents on localhost. Nothing is
// mocked. The source password never appears in the command's output.
package integration

