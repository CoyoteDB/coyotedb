const srcPassword = "src-pass-7Hq2vR9x"

// srcPG is the plain PostgreSQL being moved.
type srcPG struct {
	t    *testing.T
	inst pg.Install
	data string
	port int
}

// startSource initdbs and starts a plain Postgres: password login, sort
// order by ICU English (like most hosted Postgres, unlike CoyoteDB), and an
// extra extension folder holding "coyote_absent", an extension CoyoteDB's
// build does not have.
func startSource(t *testing.T) *srcPG {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()
	inst, err := pg.Ensure(ctx, pg.FetchOptions{CacheDir: pgCache})
	if err != nil {
		t.Fatal(err)
	}
	root := filepath.Join(t.TempDir(), "migrate-src")
	s := &srcPG{t: t, inst: inst, data: filepath.Join(root, "data"), port: freePort(t)}
	ext := filepath.Join(root, "ext", "extension")
	if err := os.MkdirAll(ext, 0o755); err != nil {
		t.Fatal(err)
	}
	write := func(p, body string) {
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write(filepath.Join(ext, "coyote_absent.control"), "comment = 'test only'\ndefault_version = '1.0'\nrelocatable = true\ntrusted = true\n")
	write(filepath.Join(ext, "coyote_absent--1.0.sql"), "CREATE FUNCTION coyote_absent_f() RETURNS int LANGUAGE sql AS 'SELECT 1';\n")
	pwfile := filepath.Join(root, "pw")
	write(pwfile, srcPassword+"\n")
	initdb := exec.Command(inst.Bin("initdb"), "-D", s.data, "-U", "postgres", "--pwfile", pwfile,
		"--auth=scram-sha-256", "--encoding=UTF8", "--locale=C", "--locale-provider=icu", "--icu-locale=en-US", "--no-sync")
	initdb.Env = withoutPGEnv()
	if out, err := initdb.CombinedOutput(); err != nil {
		t.Fatalf("initdb: %v\n%s", err, out)
	}
	conf := fmt.Sprintf("\nport = %d\nlisten_addresses = '127.0.0.1'\nunix_socket_directories = ''\nfsync = off\nwal_level = logical\n"+
		"extension_control_path = '$system:%s'\n", s.port, filepath.ToSlash(filepath.Join(root, "ext")))
	f, err := os.OpenFile(filepath.Join(s.data, "postgresql.conf"), os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatal(err)
	}
	_, _ = f.WriteString(conf)
	f.Close()
	t.Cleanup(s.stop)
	start := exec.Command(inst.Bin("pg_ctl"), "-D", s.data, "-l", filepath.Join(root, "log"), "-w", "-t", "60", "start")
	start.Env = withoutPGEnv()
	if out, err := start.CombinedOutput(); err != nil {
		b, _ := os.ReadFile(filepath.Join(root, "log"))
		t.Fatalf("start source: %v\n%s\n%s", err, out, b)
	}
	return s
}

func (s *srcPG) stop() {
	cmd := exec.Command(s.inst.Bin("pg_ctl"), "-D", s.data, "-m", "immediate", "-w", "stop")
	cmd.Env = withoutPGEnv()
	_ = cmd.Run()
}

func (s *srcPG) url(db string) string {
	return fmt.Sprintf("postgresql://postgres:%s@127.0.0.1:%d/%s?sslmode=disable", srcPassword, s.port, db)
}

func (s *srcPG) conn(db string) *pgx.Conn {
	s.t.Helper()
	c, err := tryConnect(s.url(db))
	if err != nil {
		s.t.Fatal(err)
	}
	s.t.Cleanup(func() { _ = c.Close(context.Background()) })
	return c
}

// loadShop creates database shop with tables, indexes, sequences, a
// partitioned table, a view, a function, a trigger, three extensions the
// build has, and about 100k rows.
func (s *srcPG) loadShop(scale int) {
	s.t.Helper()
	mustExec(s.t, s.conn("postgres"), "CREATE DATABASE shop")
	c := s.conn("shop")
	for _, q := range shopSQL(scale) {
		mustExec(s.t, c, q)
	}
}

// shopSQL builds the shop database's contents (PostgreSQL 12 and newer).
func shopSQL(scale int) []string {
	return []string{
		`CREATE EXTENSION citext`,
		`CREATE EXTENSION hstore`,
		`CREATE EXTENSION pg_trgm`,
		`CREATE TABLE customers (id bigserial PRIMARY KEY, email citext UNIQUE NOT NULL, name text NOT NULL,
		   created timestamptz NOT NULL, prefs hstore, balance money)`,
		`CREATE TABLE products (sku text PRIMARY KEY, title text NOT NULL, price numeric(10,2), weight float8,
		   tags text[], picture bytea)`,
		`CREATE INDEX products_title_trgm ON products USING gin (title gin_trgm_ops)`,
		`CREATE TABLE orders (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		   customer_id bigint NOT NULL REFERENCES customers, sku text NOT NULL REFERENCES products,
		   qty int NOT NULL CHECK (qty > 0), placed date NOT NULL, note jsonb)`,
		`CREATE INDEX orders_customer ON orders (customer_id)`,
		`CREATE TABLE events (id bigint NOT NULL, at timestamptz NOT NULL, what text) PARTITION BY RANGE (at)`,
		`CREATE TABLE events_2025 PARTITION OF events FOR VALUES FROM ('2025-01-01') TO ('2026-01-01')`,
		`CREATE TABLE events_2026 PARTITION OF events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')`,
		`CREATE SEQUENCE invoice_no START 1000`,
		`CREATE VIEW big_orders AS SELECT o.id, c.email, o.qty FROM orders o JOIN customers c ON c.id = o.customer_id WHERE o.qty >= 5`,
		`CREATE FUNCTION order_total(o orders) RETURNS numeric LANGUAGE sql STABLE AS
		   'SELECT o.qty * p.price FROM products p WHERE p.sku = o.sku'`,
		`CREATE FUNCTION touch_note() RETURNS trigger LANGUAGE plpgsql AS
		   $$BEGIN NEW.note := coalesce(NEW.note, '{}'::jsonb) || '{"touched": true}'; RETURN NEW; END$$`,
		`CREATE TRIGGER orders_touch BEFORE INSERT ON orders FOR EACH ROW EXECUTE FUNCTION touch_note()`,
		`COMMENT ON TABLE orders IS 'one row per order'`,
		`INSERT INTO products SELECT 'sku-' || g, 'Product ' || g || ' Ärger ñandú', (g % 500) / 3.0, g / 7.0,
		   ARRAY['t' || (g % 5), 'all'], decode(md5(g::text), 'hex') FROM generate_series(1, 1000) g`,
		fmt.Sprintf(`INSERT INTO customers (email, name, created, prefs, balance)
		   SELECT 'User' || g || '@Example.com', 'Name ' || g, timestamptz '2024-03-01 12:00+00' + g * interval '17 minutes',
		          ('theme=>dark, n=>' || g)::hstore, (g %% 1000) * 1.25
		     FROM generate_series(1, %d) g`, 20*scale),
		// Explicit ids: the identity sequence stays behind, as after a
		// bulk import; the move must set it past the highest id.
		fmt.Sprintf(`INSERT INTO orders (id, customer_id, sku, qty, placed, note)
		   SELECT g, 1 + g %% %d, 'sku-' || (1 + g %% 1000), 1 + g %% 9, date '2025-01-01' + g %% 700,
		          jsonb_build_object('n', g, 'gift', g %% 2 = 0)
		     FROM generate_series(1, %d) g`, 20*scale, 80*scale),
		`INSERT INTO events SELECT g, timestamptz '2025-06-01 00:00+00' + g * interval '3 hours', 'e' || g FROM generate_series(1, 2000) g`,
		`SELECT nextval('invoice_no') FROM generate_series(1, 42)`,
		`ANALYZE`,
	}
}

// fingerprint is an order-independent hash of a table's rows, the same on
// every server whatever its sort order or time zone.
func fingerprint(t *testing.T, c *pgx.Conn, table string) string {
	t.Helper()
	mustExec(t, c, "SET TimeZone = 'UTC'")
	return queryText(t, c, `SELECT count(*) || ':' || coalesce(md5(string_agg(h, '' ORDER BY h COLLATE "C")), '')
	   FROM (SELECT md5(x::text) AS h FROM `+table+` x) s`)
}

var shopTables = []string{"customers", "products", "orders", "events", "events_2025", "events_2026"}

// nodeDB is a superuser session on a node's own Postgres, database db.
func nodeDB(t *testing.T, n *cnode, db string) *pgx.Conn {
	t.Helper()
	c, err := tryConnect(withDB(t, n, db))
	if err != nil {
		t.Fatalf("%s: connect to %s: %v", n.name, db, err)
	}
	t.Cleanup(func() { _ = c.Close(context.Background()) })
	return c
}

// sameAsSource waits until every shop table on n matches the source.
func sameAsSource(t *testing.T, n *cnode, want map[string]string) {
	t.Helper()
	sameAsSourceIn(t, n, "app", want)
}

func sameAsSourceIn(t *testing.T, n *cnode, db string, want map[string]string) {
	t.Helper()
	waitFor(t, 90*time.Second, n.name+" has the moved data", func() bool {
		ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
		defer cancel()
		c, err := pgx.Connect(ctx, withDB(t, n, db))
		if err != nil {
			return false
		}
		defer c.Close(context.Background())
		if _, err := c.Exec(ctx, "SET TimeZone = 'UTC'"); err != nil {
			return false
		}
		for tbl, w := range want {
			var got string
			err := c.QueryRow(ctx, `SELECT count(*) || ':' || coalesce(md5(string_agg(h, '' ORDER BY h COLLATE "C")), '')
			   FROM (SELECT md5(x::text) AS h FROM `+tbl+` x) s`).Scan(&got)
			if err != nil || got != w {
				return false
			}
		}
		return true
	})
}

// migrateCmd runs `coyote migrate` against node n to completion.
func migrateCmd(t *testing.T, n *cnode, args ...string) (string, error) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()
	// The source goes in through COYOTE_MIGRATE_SOURCE, never the command
	// line (so it is not visible in ps).
	var env []string
	if len(args) > 0 && strings.HasPrefix(args[len(args)-1], "postgresql://") {
		env = append(env, "COYOTE_MIGRATE_SOURCE="+args[len(args)-1])
		args = args[:len(args)-1]
	}
	cmd := exec.CommandContext(ctx, coyoteBin, append([]string{"migrate", "--data-dir", n.dir}, args...)...)
	cmd.Env = append(append(os.Environ(), "COYOTE_PG_CACHE="+pgCache), env...)
	out, err := cmd.CombinedOutput()
	if strings.Contains(string(out), srcPassword) {
		t.Fatal("the source password appears in the command's output")
	}
	return string(out), err
}

func appURLFrom(t *testing.T, out string) string {
	t.Helper()
	_, after, ok := strings.Cut(out, "Connection string for your app:\n")
	if !ok {
		t.Fatalf("no connection string in the output:\n%s", out)
	}
	line, _, _ := strings.Cut(after, "\n")
	return strings.TrimSpace(line)
}

// userTables counts the tables in database db on n (the session is closed
// at once: an open session would keep the database from being renamed).
func userTables(t *testing.T, n *cnode, db string) int {
	t.Helper()
	c, err := tryConnect(withDB(t, n, db))
	if err != nil {
		t.Fatalf("%s: connect to %s: %v", n.name, db, err)
	}
	defer c.Close(context.Background())
	return queryInt(t, c, `SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
	   WHERE c.relkind IN ('r', 'p') AND n.nspname NOT IN ('pg_catalog', 'information_schema') AND n.nspname !~ '^pg_toast'`)
}

// Preflight (missing extension, dry run), the move into 2 data nodes + a
// witness, the check on both nodes, the app's connection string, and the
// refusal to copy over a database that is not empty.
func TestM8MigrateIntoCluster(t *testing.T) {
	src := startSource(t)
	src.loadShop(1000)
	mustExec(t, src.conn("postgres"), "CREATE DATABASE absent")
	ca := src.conn("absent")
	mustExec(t, ca, "CREATE EXTENSION coyote_absent")
	mustExec(t, ca, "CREATE TABLE t (id int PRIMARY KEY)")
	want := map[string]string{}
	sc := src.conn("shop")
	for _, tbl := range shopTables {
		want[tbl] = fingerprint(t, sc, tbl)
	}

	root := t.TempDir()
	a, b := newCNode(t, root, "node-a"), newCNode(t, root, "node-b")
	w := newWitness(t, root, "wit")
	defer stopAll(a, b, w)
	a.bootstrap()
	b.join(a)
	w.join(a)
	syncFull(t, a, b)
	b.connInfo() // the app role exists

	// A missing extension is reported before anything is copied.
	out, err := migrateCmd(t, b, "--dry-run", src.url("absent"))
	if err == nil || !strings.Contains(out, "Extension coyote_absent (version 1.0) is not part of CoyoteDB's PostgreSQL build") ||
		!strings.Contains(out, "--skip-extension coyote_absent") {
		t.Fatalf("dry run with a missing extension: err=%v\n%s", err, out)
	}
	// A clean dry run copies nothing.
	out, err = migrateCmd(t, b, "--dry-run", src.url("shop"))
	if err != nil || !strings.Contains(out, "Dry run: everything checks out. Nothing was copied.") ||
		!strings.Contains(out, "sorted by en-US on the source") {
		t.Fatalf("dry run: err=%v\n%s", err, out)
	}
	if n := userTables(t, a, "app"); n != 0 {
		t.Fatalf("a dry run created %d tables", n)
	}

	// The move, run on the copy's machine (it goes through the client
	// port to the main node, a).
	out, err = migrateCmd(t, b, src.url("shop"))
	if err != nil {
		t.Fatalf("migrate: %v\n%s", err, out)
	}
	t.Logf("migrate output:\n%s", out)
	for _, s := range []string{"5 tables match the source", "Done. Database app on the cluster now holds the copy",
		"Extensions: citext, hstore, pg_trgm", "moved past the highest id"} {
		if !strings.Contains(out, s) {
			t.Fatalf("output lacks %q:\n%s", s, out)
		}
	}
	// Same rows on both data nodes as on the source.
	sameAsSource(t, a, want)
	sameAsSource(t, b, want)

	// The printed string works for the app: TLS, the app role, the main node.
	app, err := tryConnect(appURLFrom(t, out))
	if err != nil {
		t.Fatalf("connect with the printed string: %v", err)
	}
	defer app.Close(context.Background())
	if got := queryText(t, app, "SELECT current_user || ' ' || current_database() || ' ' || pg_is_in_recovery()::text"); got != "app app false" {
		t.Fatalf("app session: %s", got)
	}
	// Sequences are past the highest id; the trigger, view, function and
	// extensions work; everything belongs to the app role.
	if id := queryInt(t, app, "INSERT INTO orders (customer_id, sku, qty, placed) VALUES (1, 'sku-1', 1, current_date) RETURNING id"); id <= 80000 {
		t.Fatalf("new order id %d collides with copied rows", id)
	}
	if got := queryText(t, app, "SELECT note->>'touched' FROM orders ORDER BY id DESC LIMIT 1"); got != "true" {
		t.Fatalf("trigger did not run: %s", got)
	}
	if got := queryInt(t, app, "SELECT nextval('invoice_no')"); got != 1042 {
		t.Fatalf("invoice_no next %d, want 1042", got)
	}
	if n := queryInt(t, app, "SELECT count(*) FROM big_orders"); n == 0 {
		t.Fatal("view is empty")
	}
	if got := queryText(t, app, "SELECT order_total(o)::text FROM orders o WHERE id = 1"); got == "" {
		t.Fatal("function")
	}
	if n := queryInt(t, app, "SELECT count(*) FROM customers WHERE email = 'user7@example.com'"); n != 1 {
		t.Fatalf("citext lookup found %d", n)
	}
	if n := queryInt(t, app, "SELECT count(*) FROM products WHERE title % 'Product 77'"); n == 0 {
		t.Fatal("pg_trgm")
	}
	if n := queryInt(t, app, `SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
	    WHERE n.nspname = 'public' AND c.relowner <> 'app'::regrole`); n != 0 {
		t.Fatalf("%d objects not owned by app", n)
	}
	if n := queryInt(t, app, "SELECT count(*) FROM pg_database WHERE datname LIKE 'app\\_\\_%'"); n != 0 {
		t.Fatalf("%d staging databases left", n)
	}

	// Not empty any more: a second run is refused and changes nothing.
	before := fingerprint(t, nodeDB(t, a, "app"), "orders")
	out, err = migrateCmd(t, b, src.url("shop"))
	if err == nil || !strings.Contains(out, "Database app on the cluster is not empty") || !strings.Contains(out, "--replace") {
		t.Fatalf("second run: err=%v\n%s", err, out)
	}
	if after := fingerprint(t, nodeDB(t, a, "app"), "orders"); after != before {
		t.Fatal("a refused run changed the data")
	}
	// --replace without a terminal and without --yes asks and is refused.
	out, err = migrateCmd(t, b, "--replace", src.url("shop"))
	if err == nil || !strings.Contains(out, "add --yes") {
		t.Fatalf("--replace without --yes: err=%v\n%s", err, out)
	}
}

// The main node is killed while the copy is being restored: the command
// stops cleanly, nothing is switched in, and a rerun with --replace on the
// new main node succeeds.
func TestM8MainKilledDuringRestore(t *testing.T) {
	src := startSource(t)
	src.loadShop(1000)
	sc := src.conn("shop")
	// Big enough that the restore takes several seconds.
	mustExec(t, sc, `CREATE TABLE ballast (id int PRIMARY KEY, a text, b text)`)
	mustExec(t, sc, `INSERT INTO ballast SELECT g, md5(g::text), repeat('x', 200) FROM generate_series(1, 800000) g`)
	want := map[string]string{"ballast": fingerprint(t, sc, "ballast")}
	for _, tbl := range shopTables {
		want[tbl] = fingerprint(t, sc, tbl)
	}

	root := t.TempDir()
	a, b := newCNode(t, root, "node-a"), newCNode(t, root, "node-b")
	w := newWitness(t, root, "wit")
	defer stopAll(a, b, w)
	a.bootstrap()
	b.join(a)
	w.join(a)
	syncFull(t, a, b)
	b.connInfo()

	out := &syncBuffer{}
	// This one reads the source from stdin, the default without an argument.
	cmd := exec.Command(coyoteBin, "migrate", "--data-dir", b.dir)
	cmd.Env = append(os.Environ(), "COYOTE_PG_CACHE="+pgCache)
	cmd.Stdin = strings.NewReader(src.url("shop") + "\n")
	cmd.Stdout, cmd.Stderr = out, out
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	exited := make(chan error, 1)
	go func() { exited <- cmd.Wait() }()
	t.Cleanup(func() {
		if cmd.ProcessState == nil {
			_ = cmd.Process.Kill()
		}
	})
	waitFor(t, 5*time.Minute, "the restore to start", func() bool {
		return strings.Contains(out.String(), "Copying into the cluster")
	})
	noPasswordInPS(t)
	// Data is going in: the staging database is being filled on a.
	waitFor(t, 60*time.Second, "rows arriving on the main node", func() bool {
		c, err := tryConnect(withDB(t, a, "app__migrating"))
		if err != nil {
			return false
		}
		defer c.Close(context.Background())
		var n int64
		err = c.QueryRow(context.Background(), "SELECT pg_database_size(current_database())").Scan(&n)
		return err == nil && n > 40<<20
	})
	if strings.Contains(out.String(), "Checking the copy") {
		t.Fatalf("the restore finished before the kill; make the ballast bigger:\n%s", out.String())
	}
	a.killAgent()
	var werr error
	select {
	case werr = <-exited:
	case <-time.After(3 * time.Minute):
		t.Fatalf("migrate did not stop after the main node was killed:\n%s", out.String())
	}
	o := out.String()
	t.Logf("migrate output after the kill:\n%s", o)
	if werr == nil || !strings.Contains(o, "Nothing was switched in: database app is unchanged") {
		t.Fatalf("migrate after the kill: err=%v\n%s", werr, o)
	}
	if strings.Contains(o, "Done.") || strings.Contains(o, srcPassword) {
		t.Fatalf("unexpected output:\n%s", o)
	}
	// b takes over; its app database shows nothing half-done.
	waitFor(t, 90*time.Second, "node-b to become the main node", func() bool {
		return b.isPrimary() && b.clusterStatus().Cluster.PrimaryName == b.name
	})
	if n := userTables(t, b, "app"); n != 0 {
		t.Fatalf("app database on the new main node has %d tables after the failed move", n)
	}

	res, err := migrateCmd(t, b, "--replace", "--yes", src.url("shop"))
	if err != nil {
		t.Fatalf("rerun: %v\n%s", err, res)
	}
	if !strings.Contains(res, "6 tables match the source") || !strings.Contains(res, "main node node-b") {
		t.Fatalf("rerun output:\n%s", res)
	}
	sameAsSource(t, b, want)
	app, err := tryConnect(appURLFrom(t, res))
	if err != nil {
		t.Fatal(err)
	}
	defer app.Close(context.Background())
	if n := queryInt(t, app, "SELECT count(*) FROM pg_database WHERE datname LIKE 'app\\_\\_%'"); n != 0 {
		t.Fatalf("%d staging databases left after the rerun", n)
	}
}

// withDB is n's superuser URL for database db.
func withDB(t *testing.T, n *cnode, db string) string {
	t.Helper()
	out, err := n.cli("conninfo", "--admin")
	if err != nil {
		t.Fatalf("conninfo --admin: %v", err)
	}
	u, err := url.Parse(strings.TrimSpace(out))
	if err != nil {
		t.Fatal(err)
	}
	u.Path = "/" + db
	return u.String()
}

// noPasswordInPS fails if the source password is on any command line.
func noPasswordInPS(t *testing.T) {
	t.Helper()
	out, err := exec.Command("ps", "-axww", "-o", "command=").Output()
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(out), srcPassword) {
		t.Fatal("the source password is visible in ps")
	}
}
